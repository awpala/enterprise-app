#!/usr/bin/env node
/**
 * Generates ui/src/app/environments/environment.ts at build time.
 *
 * Reads API_URL from:
 *   1. process.env.API_URL (set by the caller / CI), or
 *   2. the repo-root .env file (via dotenv), if present.
 *
 * Modes:
 *   - default (no flag): writes a safe default (apiUrl: '') if API_URL is unset.
 *     Invoked by `postinstall` so clones / `npm ci` always produce a valid file
 *     that satisfies angular.json fileReplacements.
 *   - --require-api-url: fails with a non-zero exit if API_URL is unset.
 *     Invoked by `build:prod` to guarantee production builds never ship empty.
 */

import { writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..', '..');
const envFile = resolve(repoRoot, '.env');
const outFile = resolve(__dirname, '..', 'src', 'app', 'environments', 'environment.ts');

// Minimal dotenv-style loader (no dependency required).
// Only populates keys not already present in process.env.
if (existsSync(envFile)) {
  const raw = readFileSync(envFile, 'utf8');
  for (const line of raw.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) {
      process.env[key] = value;
    }
  }
}

const requireApiUrl = process.argv.includes('--require-api-url');
const apiUrl = (process.env.API_URL ?? '').trim();

if (requireApiUrl && !apiUrl) {
  console.error(
    '[generate-environment] ERROR: API_URL is not set.\n' +
      '  Set it in your environment or in /workspace/.env before running a production build.\n' +
      '  Example:  export API_URL="https://<api-fqdn>" && npm run build:prod'
  );
  process.exit(1);
}

const contents = `/**
 * Production environment configuration.
 *
 * AUTO-GENERATED by ui/scripts/generate-environment.mjs — DO NOT EDIT BY HAND.
 * This file is gitignored. The apiUrl value is sourced from the API_URL env var
 * (or the repo-root .env file) at build time.
 */
export const environment = {
  production: true,
  apiUrl: ${JSON.stringify(apiUrl)},
};
`;

writeFileSync(outFile, contents, 'utf8');
console.log(
  `[generate-environment] wrote ${outFile} (apiUrl=${apiUrl ? apiUrl : '<empty>'})`
);
