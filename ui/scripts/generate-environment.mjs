#!/usr/bin/env node
/**
 * Generates ui/src/app/environments/environment.ts at build time.
 *
 * Reads values from:
 *   1. process.env.* (set by the caller / CI), or
 *   2. the repo-root .env file (via the inlined dotenv loader), if present.
 *
 * Variables consumed:
 *   - API_URL         (required with --require-api-url)
 *   - AAD_AUTHORITY   — Entra External ID OIDC authority URL
 *   - AAD_CLIENT_ID   — SPA app registration client id
 *   - AAD_TENANT_ID   — External ID tenant id (GUID)
 *   - AAD_API_SCOPE   — fully-qualified API scope URI passed to MSAL
 *   - ENABLE_DEV_AUTH — "true" to expose the "Log in as Dev" affordance on
 *     the landing page. Enables a synthetic session that matches the backend
 *     DevAuthHandler's sentinel principal. Must be "false"/unset for prod.
 *
 * Modes:
 *   - default (no flag): writes a safe default (empty strings) for any
 *     missing value. Invoked by `postinstall` so clones / `npm ci` always
 *     produce a valid file that satisfies angular.json fileReplacements.
 *   - --require-api-url: fails with a non-zero exit if API_URL is unset.
 *     Invoked by `build:prod` to guarantee production builds never ship
 *     empty. AAD_* values are NOT strictly required at build time — MSAL
 *     initialization will fail at runtime if they are blank, which is the
 *     correct failure mode for a missing infra bootstrap.
 */

import { writeFileSync, existsSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..', '..');
const envFile = resolve(repoRoot, '.env');
const outFile = resolve(__dirname, '..', 'src', 'app', 'environments', 'environment.ts');

// Minimal dotenv-style loader (no dependency required).
// Only populates keys not already present in process.env.
if (existsSync(envFile)) {
  const raw = readFileSync(envFile, 'utf8');
  for (const line of raw.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (process.env[key] === undefined) {
      process.env[key] = value;
    }
  }
}

const requireApiUrl = process.argv.includes('--require-api-url');
const apiUrl = (process.env.API_URL ?? '').trim();
const aadAuthority = (process.env.AAD_AUTHORITY ?? '').trim();
const aadClientId = (process.env.AAD_CLIENT_ID ?? '').trim();
const aadTenantId = (process.env.AAD_TENANT_ID ?? '').trim();
const aadApiScope = (process.env.AAD_API_SCOPE ?? '').trim();
const enableDevAuth = (process.env.ENABLE_DEV_AUTH ?? '').trim().toLowerCase() === 'true';

if (requireApiUrl && !apiUrl) {
  console.error(
    '[generate-environment] ERROR: API_URL is not set.\n' +
      '  Set it in your environment or in /workspace/.env before running a production build.\n' +
      '  Example:  export API_URL="https://<api-fqdn>" && npm run build:prod'
  );
  process.exit(1);
}

const contents = `/**
 * Production environment configuration.
 *
 * AUTO-GENERATED by ui/scripts/generate-environment.mjs — DO NOT EDIT BY HAND.
 * This file is gitignored. Values are sourced from env vars (or the repo-root
 * .env file) at build time.
 */
export const environment = {
  production: true,
  apiUrl: ${JSON.stringify(apiUrl)},
  aadAuthority: ${JSON.stringify(aadAuthority)},
  aadClientId: ${JSON.stringify(aadClientId)},
  aadTenantId: ${JSON.stringify(aadTenantId)},
  aadApiScope: ${JSON.stringify(aadApiScope)},
  enableDevAuth: ${JSON.stringify(enableDevAuth)},
};
`;

writeFileSync(outFile, contents, 'utf8');
console.log(
  `[generate-environment] wrote ${outFile}\n` +
    `  apiUrl=${apiUrl ? apiUrl : '<empty>'}\n` +
    `  aadAuthority=${aadAuthority ? aadAuthority : '<empty>'}\n` +
    `  aadClientId=${aadClientId ? aadClientId : '<empty>'}\n` +
    `  aadTenantId=${aadTenantId ? aadTenantId : '<empty>'}\n` +
    `  aadApiScope=${aadApiScope ? aadApiScope : '<empty>'}\n` +
    `  enableDevAuth=${enableDevAuth}`
);
